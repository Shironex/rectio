/** A motion add-on item: pro, installed under `@ui/motion/` beside the plain components. */
const motionItem = (
  name: string,
  title: string,
  description: string,
  files: string[],
  type: 'component' | 'lib' = 'component',
  version = '0.1.0',
) => ({
  name: `motion-${name}`,
  type,
  tier: 'pro' as const,
  version,
  title,
  description,
  categories: ['motion'],
  files,
});

/** A finance block: pro, installed under `@blocks/finance/`, with its motioned twin beside it. */
const blockItems = (
  name: string,
  title: string,
  description: string,
  folder: string,
  file: string,
) => [
  {
    name,
    type: 'block' as const,
    tier: 'pro' as const,
    version: '0.1.0',
    title,
    description,
    categories: ['finance', 'blocks'],
    files: [`${folder}/${file}.tsx`, `${folder}/${folder}.logic.ts`],
  },
  {
    name: `motion-${name}`,
    type: 'block' as const,
    tier: 'pro' as const,
    version: '0.1.0',
    title: `Motion ${title}`,
    description: `${title} with entrances that play once, on first view.`,
    categories: ['finance', 'blocks', 'motion'],
    files: [`${folder}/${file}.motion.tsx`],
  },
];

/**
 * A marketing block: pro, installed under `@blocks/marketing/`. `logic` adds its logic file; `motion`
 * adds a `motion-<name>` twin for blocks with something to animate.
 */
const marketingItems = (
  name: string,
  title: string,
  description: string,
  folder: string,
  { logic = false, motion = true }: { logic?: boolean; motion?: boolean } = {},
) => [
  {
    name,
    type: 'block' as const,
    tier: 'pro' as const,
    version: '0.1.0',
    title,
    description,
    categories: ['marketing', 'blocks'],
    files: [`${folder}/${folder}.tsx`, ...(logic ? [`${folder}/${folder}.logic.ts`] : [])],
  },
  ...(motion
    ? [
        {
          name: `motion-${name}`,
          type: 'block' as const,
          tier: 'pro' as const,
          version: '0.1.0',
          title: `Motion ${title}`,
          description: `${title} with entrances that play once, on first view.`,
          categories: ['marketing', 'blocks', 'motion'],
          files: [`${folder}/${folder}.motion.tsx`],
          // It calls the motion core at module level, so Next must treat it as a client module.
          client: true,
        },
      ]
    : []),
];

