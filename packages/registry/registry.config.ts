/** A motion add-on item, installed under `@ui/motion/` beside the plain components. */
const motionItem = (
  name: string,
  title: string,
  description: string,
  files: string[],
  type: 'component' | 'lib' = 'component',
  version = '0.1.0',
) => ({
  name: `motion-${name}`,
  type,
  version,
  title,
  description,
  categories: ['motion'],
  files,
});

/** A finance block, installed under `@blocks/finance/`, with its motioned twin beside it. */
const blockItems = (
  name: string,
  title: string,
  description: string,
  folder: string,
  file: string,
  version = '0.1.0',
) => [
  {
    name,
    type: 'block' as const,
    version,
    title,
    description,
    categories: ['finance', 'blocks'],
    files: [`${folder}/${file}.tsx`, `${folder}/${folder}.logic.ts`],
  },
  {
    name: `motion-${name}`,
    type: 'block' as const,
    version: '0.1.0',
    title: `Motion ${title}`,
    description: `${title} with entrances that play once, on first view.`,
    categories: ['finance', 'blocks', 'motion'],
    files: [`${folder}/${file}.motion.tsx`],
  },
];

/**
 * A SaaS or app block, installed under `@blocks/saas/`, with its motioned twin beside it. `version`
 * is the plain item's and `motionVersion` the twin's; bump each when its files change.
 */
const saasItems = (
  name: string,
  title: string,
  description: string,
  { version = '0.1.0', motionVersion = '0.1.0' }: { version?: string; motionVersion?: string } = {},
) => [
  {
    name,
    type: 'block' as const,
    version,
    title,
    description,
    categories: ['saas', 'blocks'],
    files: [`${name}/${name}.tsx`, `${name}/${name}.logic.ts`],
  },
  {
    name: `motion-${name}`,
    type: 'block' as const,
    version: motionVersion,
    title: `Motion ${title}`,
    description: `${title} with entrances that play once and list items that arrive and leave in place.`,
    categories: ['saas', 'blocks', 'motion'],
    files: [`${name}/${name}.motion.tsx`],
  },
];

/**
 * A marketing block, installed under `@blocks/marketing/`. `logic` adds its logic file; `motion`
 * adds a `motion-<name>` twin for blocks with something to animate.
 */
const marketingItems = (
  name: string,
  title: string,
  description: string,
  folder: string,
  {
    logic = false,
    motion = true,
    extra = [],
    version = '0.1.0',
  }: { logic?: boolean; motion?: boolean; extra?: readonly string[]; version?: string } = {},
) => [
  {
    name,
    type: 'block' as const,
    version,
    title,
    description,
    categories: ['marketing', 'blocks'],
    files: [
      `${folder}/${folder}.tsx`,
      ...extra,
      ...(logic ? [`${folder}/${folder}.logic.ts`] : []),
    ],
    // The source decides: interactive files carry their own 'use client', static blocks stay
    // server components and ship no JavaScript.
    client: false,
  },
  ...(motion
    ? [
        {
          name: `motion-${name}`,
          type: 'block' as const,
          version: '0.1.0',
          title: `Motion ${title}`,
          description: `${title} with entrances that play once, on first view.`,
          categories: ['marketing', 'blocks', 'motion'],
          files: [`${folder}/${folder}.motion.tsx`],
          // It calls the motion core at module level, so Next must treat it as a client module.
          client: true,
        },
      ]
    : []),
];

/**
 * A docs block, installed under `@blocks/docs/`. `files` overrides the default
 * `<folder>/<folder>.tsx`; `logic` adds its logic file; `motion` adds a `motion-<name>` twin for
 * blocks with something to animate.
 */
const docsItems = (
  name: string,
  title: string,
  description: string,
  folder: string,
  {
    logic = false,
    motion = false,
    files,
  }: { logic?: boolean; motion?: boolean; files?: string[] } = {},
) => [
  {
    name,
    type: 'block' as const,
    version: '0.1.0',
    title,
    description,
    categories: ['docs', 'blocks'],
    files: [
      ...(files ?? [`${folder}/${folder}.tsx`]),
      ...(logic ? [`${folder}/${folder}.logic.ts`] : []),
    ],
  },
  ...(motion
    ? [
        {
          name: `motion-${name}`,
          type: 'block' as const,
          version: '0.1.0',
          title: `Motion ${title}`,
          description: `${title} with the motion parts: entrances once on first view, gliding indicators.`,
          categories: ['docs', 'blocks', 'motion'],
          files: [`${folder}/${folder}.motion.tsx`],
          client: true,
        },
      ]
    : []),
];

